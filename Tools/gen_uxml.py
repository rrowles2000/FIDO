# Regenerate the C# that Unity's [UxmlElement] source generator emitted into a shipped K2D2.dll,
# from its ikdasm listing. Needed because the plain-csc build (Tools/build.sh) has no generator.
# Usage: python3 gen_uxml.py K2D2.il > Generated/UxmlSerializedData.g.cs
import re, sys
lines = open(sys.argv[1]).read().split('\n')
TYPES = {'float32':'float','float64':'double','string':'string','bool':'bool','int32':'int','int64':'long','uint32':'uint'}
def cstype(t):
    t = t.strip()
    if t in TYPES: return TYPES[t]
    m = re.match(r'(?:valuetype|class)\s+(?:\[[^\]]+\])?(.+)$', t)
    if m: t = m.group(1)
    t = re.sub(r'^\[[^\]]+\]', '', t)
    return 'global::' + t.replace('/', '.')
def bytes_str(blob):
    b = bytes(int(x,16) for x in blob.split())
    n = b[2]; return b[3:3+n].decode()
out = []; outer = None; i = 0
while i < len(lines):
    l = lines[i]
    m = re.match(r'^\.class .* ([\w.]+)$', l)
    if m: outer = m.group(1)
    if re.match(r'^  \.class .*nested public beforefieldinit UxmlSerializedData$', l):
        ext = re.search(r'extends\s+(?:\[[^\]]+\])?(\S+)', lines[i+1]).group(1).replace('/', '.')
        fields = []; j = i + 2
        while not lines[j].startswith('  } // end of class UxmlSerializedData'):
            fm = re.match(r'^    \.field private (.+) (\'?[\w]+\'?)$', lines[j])
            if fm and not fm.group(2).endswith('_UxmlAttributeFlags'):
                name = fm.group(2).strip("'"); attr = None; cp = False
                k = j + 1; blob = ''
                while k < len(lines) and lines[k].strip().startswith('.custom'):
                    if 'CreatePropertyAttribute' in lines[k]: cp = True
                    if 'UxmlAttributeAttribute::.ctor(string)' in lines[k]:
                        blob = lines[k].split('( ',1)[1].split(')')[0].split('//')[0]
                        kk = k + 1
                        while '(' not in lines[kk] and lines[kk].strip() and not lines[kk].strip().startswith('.'):
                            blob += ' ' + lines[kk].split('//')[0].replace(')', ''); kk += 1
                        attr = bytes_str(blob)
                    k += 1
                fields.append((cstype(fm.group(1)), name, attr, cp))
            j += 1
        ns, _, cls = outer.rpartition('.')
        base = ext if ext.startswith(('UnityEngine', 'K2')) else ext
        if base.startswith('UnityEngine.UIElements.'): base = base[len('UnityEngine.UIElements.'):]
        base = re.sub(r'^(\w+)`1\.UxmlSerializedData<(.+)>$', lambda mm: mm.group(1) + '<' + TYPES.get(mm.group(2), mm.group(2)) + '>.UxmlSerializedData', base)
        out.append(f'namespace {ns}\n{{\n    public partial class {cls}\n    {{\n        [global::System.Serializable]\n        public new class UxmlSerializedData : {base}\n        {{')
        for t, n, a, cp in fields:
            attrs = (['global::Unity.Properties.CreateProperty'] if cp else []) + ([f'UxmlAttribute("{a}")'] if a else []) + ['SerializeField']
            out.append(f'            [{", ".join(attrs)}] private {t} @{n};')
        for t, n, a, cp in fields:
            out.append(f'            [SerializeField, UxmlIgnore, HideInInspector] private UxmlAttributeFlags {n}_UxmlAttributeFlags;')
        out.append(f'\n            public override object CreateInstance() => new {cls}();\n\n            public override void Deserialize(object obj)\n            {{\n                base.Deserialize(obj);\n                var e = ({cls})obj;')
        for t, n, a, cp in fields:
            out.append(f'                if (ShouldWriteAttributeValue({n}_UxmlAttributeFlags)) e.@{n} = @{n};')
        out.append('            }\n        }\n    }\n}\n')
        i = j
    i += 1
print('// Generated by Tools/gen_uxml.py from the shipped K2D2 1.3.0 DLL: the code Unity\'s [UxmlElement]\n// source generator emits. Only for the plain-csc build; the Unity editor generates this itself.\nusing UnityEngine;\nusing UnityEngine.UIElements;\n')
print('\n'.join(out))
